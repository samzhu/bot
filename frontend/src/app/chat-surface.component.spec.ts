import { TestBed } from '@angular/core/testing';
import { describe, expect, it, vi } from 'vitest';
import { completeDelivery, mockAgent, staticDelivery } from '@threadplane/chat';
import { ChatSurfaceComponent } from './chat-surface.component';
import { signal } from '@angular/core';

describe('ChatSurfaceComponent', () => {
  it.each([['MONTH_CAP','預算'],['MONTH_UNKNOWN','費用']])('shows a safe budget denial for %s', async (reason, expected) => {
    const fixture = TestBed.createComponent(ChatSurfaceComponent);
    fixture.componentRef.setInput('agent', mockAgent());
    fixture.componentRef.setInput('runFailed', true);
    fixture.componentRef.setInput('runDenialReason', reason);
    fixture.detectChanges(); await fixture.whenStable(); fixture.detectChanges();
    expect(fixture.nativeElement.textContent).toContain(expected);
    expect(fixture.nativeElement.textContent).not.toContain('untrusted server text');
  });
  it('shows cancellation even when no assistant message was produced', async () => {
    const fixture = TestBed.createComponent(ChatSurfaceComponent);
    fixture.componentRef.setInput('agent', mockAgent());
    fixture.componentRef.setInput('runCancelled', true);
    fixture.detectChanges(); await fixture.whenStable();
    expect(fixture.nativeElement.textContent).toContain('回覆已停止');
  });
  it('shows a stopped partial response without a retry action', async () => {
    const fixture = TestBed.createComponent(ChatSurfaceComponent);
    fixture.componentRef.setInput('agent', mockAgent({messages:[{id:'a',role:'assistant',content:'partial',delivery:completeDelivery('a','aborted')}]}));
    fixture.detectChanges(); await fixture.whenStable();
    expect(fixture.nativeElement.textContent).toContain('回覆已停止');
    expect(fixture.nativeElement.textContent).not.toContain('Retry');
  });
  it('copies through the clipboard and reports success and failure', async () => {
    const fixture = TestBed.createComponent(ChatSurfaceComponent);
    fixture.componentRef.setInput('agent', mockAgent({messages:[{id:'a',role:'assistant',content:'answer',delivery:staticDelivery('a')}]}));
    fixture.detectChanges();
    await fixture.whenStable();
    const writeText = vi.fn().mockResolvedValueOnce(undefined).mockRejectedValueOnce(new Error('denied'));
    Object.defineProperty(navigator, 'clipboard', {value:{writeText}, configurable:true});
    const copy = fixture.nativeElement.querySelector('button[aria-label="複製回覆"]') as HTMLButtonElement;
    copy.click();
    await fixture.whenStable();
    fixture.detectChanges();
    expect(writeText).toHaveBeenCalledWith('answer');
    expect(fixture.nativeElement.textContent).toContain('已複製回覆');
    copy.click();
    await fixture.whenStable();
    fixture.detectChanges();
    expect(fixture.nativeElement.textContent).toContain('無法複製回覆');
    Reflect.deleteProperty(navigator, 'clipboard');
  });
  it('offers read-only status check for unknown outcome without retry', async () => {
    const fixture = TestBed.createComponent(ChatSurfaceComponent);
    fixture.componentRef.setInput('agent', mockAgent());
    fixture.componentRef.setInput('runUnknown', true);
    const check = vi.fn();
    fixture.componentInstance.checkStatusRequested.subscribe(check);
    fixture.detectChanges();
    await fixture.whenStable();
    const root = fixture.nativeElement as HTMLElement;
    expect(root.querySelector('chat-window')).toBeTruthy();
    expect(root.querySelector('chat-error')).toBeTruthy();
    const button = [...root.querySelectorAll('chat-error button')].find(el => el.textContent?.includes('Check status'));
    expect(button).toBeTruthy();
    (button as HTMLButtonElement).click();
    expect(check).toHaveBeenCalledOnce();
    expect(root.textContent).not.toContain('Retry');
  });
  it('keeps the same raw draft when a parent declines submission', async () => {
    const fixture = TestBed.createComponent(ChatSurfaceComponent);
    fixture.componentRef.setInput('agent', mockAgent());
    fixture.componentRef.setInput('draft', '  unchanged  ');
    fixture.detectChanges();
    await fixture.whenStable();
    const textarea = fixture.nativeElement.querySelector('textarea') as HTMLTextAreaElement;
    (fixture.nativeElement.querySelector('chat-input button[aria-label="Send message"]') as HTMLButtonElement).click();
    await fixture.whenStable();
    fixture.detectChanges();
    expect(textarea.value).toBe('  unchanged  ');
  });
  it('restores the same draft after a failed submission even when updates coalesce', async () => {
    const fixture = TestBed.createComponent(ChatSurfaceComponent);
    fixture.componentRef.setInput('agent', mockAgent());
    fixture.componentRef.setInput('draft', '  same  ');
    fixture.componentInstance.submitRequested.subscribe(() => {
      fixture.componentRef.setInput('draft', '');
      fixture.componentRef.setInput('draft', '  same  ');
    });
    fixture.detectChanges();
    await fixture.whenStable();
    (fixture.nativeElement.querySelector('chat-input button[aria-label="Send message"]') as HTMLButtonElement).click();
    await fixture.whenStable();
    fixture.detectChanges();
    expect((fixture.nativeElement.querySelector('textarea') as HTMLTextAreaElement).value).toBe('  same  ');
  });
  it('honours both application and adapter input blocks without clearing the draft', async () => {
    const fixture = TestBed.createComponent(ChatSurfaceComponent);
    const blocked = signal(true);
    const agent = { ...mockAgent(), isInputBlocked: blocked };
    fixture.componentRef.setInput('agent', agent);
    fixture.componentRef.setInput('draft', '  draft  ');
    fixture.componentRef.setInput('inputBlocked', false);
    const submitted = vi.fn();
    fixture.componentInstance.submitRequested.subscribe(submitted);
    fixture.detectChanges();
    await fixture.whenStable();
    const textarea = fixture.nativeElement.querySelector('textarea') as HTMLTextAreaElement;
    textarea.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
    fixture.detectChanges();
    expect(submitted).not.toHaveBeenCalled();
    expect(textarea.value).toBe('  draft  ');
    blocked.set(false);
    fixture.componentRef.setInput('inputBlocked', true);
    fixture.detectChanges();
    textarea.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
    expect(submitted).not.toHaveBeenCalled();
    expect(textarea.value).toBe('  draft  ');
  });
  it('uses native primitives, emits the raw draft and omits unimplemented controls', async () => {
    const fixture = TestBed.createComponent(ChatSurfaceComponent);
    const agent = mockAgent({ messages: [{id:'a', role:'assistant', content:'**answer**', delivery:staticDelivery('a')}] });
    fixture.componentRef.setInput('agent', agent);
    fixture.componentRef.setInput('draft', '');
    fixture.componentRef.setInput('inputBlocked', false);
    const submit = vi.fn();
    fixture.componentInstance.submitRequested.subscribe(submit);
    fixture.detectChanges();
    await fixture.whenStable();
    const root = fixture.nativeElement as HTMLElement;
    const textarea = root.querySelector('chat-input textarea') as HTMLTextAreaElement;
    textarea.value = '  hello\n  ';
    textarea.dispatchEvent(new Event('input', {bubbles:true}));
    fixture.detectChanges();
    (root.querySelector('chat-input button[aria-label="Send message"]') as HTMLButtonElement).click();
    expect(submit).toHaveBeenCalledWith('  hello\n  ');
    expect(root.querySelector('chat-message-list')).toBeTruthy();
    expect(root.querySelector('chat-streaming-md')).toBeTruthy();
    expect(root.querySelector('chat-message-actions')).toBeNull();
  });
});
