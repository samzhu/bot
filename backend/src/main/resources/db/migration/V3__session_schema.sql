CREATE TABLE IF NOT EXISTS AI_SESSION (
    id            VARCHAR(255)  NOT NULL PRIMARY KEY,
    created_at    TIMESTAMP     NOT NULL,
    expires_at    TIMESTAMP,
    metadata      TEXT          NOT NULL,
    event_version BIGINT        NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_ai_session_expires_at
    ON AI_SESSION (expires_at);

COMMENT ON TABLE AI_SESSION IS 'Spring AI 2.1 Session JDBC 核心狀態表，儲存模型續聊之脈絡工作區。';
COMMENT ON COLUMN AI_SESSION.id IS 'Session 識別碼（主鍵，1:1 對齊 conversation_id）。';
COMMENT ON COLUMN AI_SESSION.created_at IS 'Session 建立時間戳記。';
COMMENT ON COLUMN AI_SESSION.expires_at IS 'Session 過期時間戳記（可為空表示不過期）。';
COMMENT ON COLUMN AI_SESSION.metadata IS 'Session 屬性 JSON 字串（如 principalName 等）。';
COMMENT ON COLUMN AI_SESSION.event_version IS '樂觀鎖事件版本號，每次追加事件時遞增。';

-- Indexed metadata attributes: one row per session and indexed attribute name (by
-- default the principal name). findByIndex(name, value) is one query over this table.
CREATE TABLE IF NOT EXISTS AI_SESSION_INDEX (
    session_id    VARCHAR(255)  NOT NULL,
    attr_name     VARCHAR(255)  NOT NULL,
    attr_value    VARCHAR(512)  NOT NULL,
    PRIMARY KEY (session_id, attr_name),
    CONSTRAINT fk_ai_session_index_session
        FOREIGN KEY (session_id) REFERENCES AI_SESSION (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_ai_session_index_name_value
    ON AI_SESSION_INDEX (attr_name, attr_value);

COMMENT ON TABLE AI_SESSION_INDEX IS 'Spring AI 2.1 Session 屬性索引表，提供基於屬性（如 user）之快速查詢。';
COMMENT ON COLUMN AI_SESSION_INDEX.session_id IS '所屬 Session 識別碼，外鍵參照 ai_session(id)。';
COMMENT ON COLUMN AI_SESSION_INDEX.attr_name IS '索引屬性名稱，例如 principalName。';
COMMENT ON COLUMN AI_SESSION_INDEX.attr_value IS '索引屬性字串值，例如 dev-user。';

CREATE TABLE IF NOT EXISTS AI_SESSION_EVENT (
    seq             BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    id              VARCHAR(255)  NOT NULL PRIMARY KEY,
    session_id      VARCHAR(255)  NOT NULL,
    "timestamp"     TIMESTAMP     NOT NULL,
    -- Sized for EventType.MAX_NAME_LENGTH
    event_type      VARCHAR(64)   NOT NULL DEFAULT 'MESSAGE',
    -- NULL for an event that is not a message
    message_type    VARCHAR(20),
    message_content TEXT,
    -- Message parts and metadata, or the payload of an event that is not a message
    payload         TEXT          NOT NULL,
    synthetic       BOOLEAN       NOT NULL DEFAULT FALSE,
    metadata        TEXT          NOT NULL,
    CONSTRAINT fk_ai_session_event_session
        FOREIGN KEY (session_id) REFERENCES AI_SESSION (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_ai_session_event_session_seq
    ON AI_SESSION_EVENT (session_id, seq);

-- The newest compaction boundary of a session, on every read of the active view
CREATE INDEX IF NOT EXISTS idx_ai_session_event_session_type_seq
    ON AI_SESSION_EVENT (session_id, event_type, seq);

COMMENT ON TABLE AI_SESSION_EVENT IS 'Spring AI 2.1 Session 事件串流表，記錄成功輪次之對話記憶。';
COMMENT ON COLUMN AI_SESSION_EVENT.seq IS '事件序號（自增流水號）。';
COMMENT ON COLUMN AI_SESSION_EVENT.id IS '事件識別碼（主鍵）。';
COMMENT ON COLUMN AI_SESSION_EVENT.session_id IS '所屬 Session 識別碼，外鍵參照 ai_session(id)。';
COMMENT ON COLUMN AI_SESSION_EVENT."timestamp" IS '事件發生時間戳記。';
COMMENT ON COLUMN AI_SESSION_EVENT.event_type IS '事件類型，預設為 MESSAGE。';
COMMENT ON COLUMN AI_SESSION_EVENT.message_type IS '訊息類型，例如 USER 或 ASSISTANT。';
COMMENT ON COLUMN AI_SESSION_EVENT.message_content IS '訊息文字內容。';
COMMENT ON COLUMN AI_SESSION_EVENT.payload IS '事件完整序列化 JSON 內容（包含元資料與額外 parts）。';
COMMENT ON COLUMN AI_SESSION_EVENT.synthetic IS '是否為系統合成之事件（如壓縮摘要邊界）。';
COMMENT ON COLUMN AI_SESSION_EVENT.metadata IS '事件附帶之額外元資料 JSON 字串。';
